-- Supabase Schema for ConcertScout (Scout Overhaul)

-- Enable pgcrypto for gen_random_uuid() if available
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. Weekly Submissions Table
CREATE TABLE IF NOT EXISTS weekly_submissions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    week VARCHAR NOT NULL,
    band_name VARCHAR NOT NULL,
    direct_views INT DEFAULT 0,
    indirect_views INT DEFAULT 0,
    total_saves INT DEFAULT 0,
    interaction_type VARCHAR DEFAULT 'none',
    interaction_score INT DEFAULT 0,
    shared BOOLEAN DEFAULT false,
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Band Registry Table
CREATE TABLE IF NOT EXISTS band_registry (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    band_name VARCHAR UNIQUE NOT NULL,
    primary_genre VARCHAR,
    spotify_id VARCHAR,
    total_listeners INT DEFAULT 0,
    last_used_in_playlist VARCHAR,
    ever_featured_in_top50 BOOLEAN DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Tour Events Table
CREATE TABLE IF NOT EXISTS tour_events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    band_name VARCHAR NOT NULL,
    venue VARCHAR NOT NULL,
    city VARCHAR NOT NULL,
    country VARCHAR NOT NULL,
    event_date DATE NOT NULL,
    last_fm_url VARCHAR,
    source VARCHAR DEFAULT 'last.fm',
    scraped_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_band_venue_date UNIQUE (band_name, venue, event_date)
);

-- Legacy tables maintained for backward compatibility
CREATE TABLE IF NOT EXISTS artists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    spotify_id TEXT,
    instagram_url TEXT,
    lastfm_url TEXT,
    source_playlist TEXT,
    is_active BOOLEAN DEFAULT true,
    added_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    last_scraped_at TIMESTAMP WITH TIME ZONE,
    last_instagram_post_id TEXT
);

CREATE TABLE IF NOT EXISTS concerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id BIGINT REFERENCES artists(id) ON DELETE CASCADE,
    event_name TEXT NOT NULL,
    city TEXT NOT NULL,
    venue TEXT NOT NULL,
    event_date DATE NOT NULL,
    ticket_url TEXT,
    source TEXT DEFAULT 'lastfm',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_artist_date_city UNIQUE (artist_id, event_date, city)
);

CREATE TABLE IF NOT EXISTS playlist_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id TEXT UNIQUE NOT NULL,
    track_name TEXT NOT NULL,
    artist_id TEXT NOT NULL,
    artist_name TEXT NOT NULL,
    tier TEXT NOT NULL,
    monthly_listeners BIGINT,
    release_date DATE,
    added_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS on all tables
ALTER TABLE weekly_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE band_registry ENABLE ROW LEVEL SECURITY;
ALTER TABLE tour_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE artists ENABLE ROW LEVEL SECURITY;
ALTER TABLE concerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE playlist_history ENABLE ROW LEVEL SECURITY;

