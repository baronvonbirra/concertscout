-- Supabase Schema for ConcertScout (Scout v2.0)

-- Artists table
CREATE TABLE IF NOT EXISTS artists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    spotify_id TEXT,
    instagram_url TEXT,
    lastfm_url TEXT,
    source_playlist TEXT,
    is_active BOOLEAN DEFAULT true,
    added_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    last_scraped_at TIMESTAMP WITH TIME ZONE,
    last_instagram_post_id TEXT
);

-- Concerts table
CREATE TABLE IF NOT EXISTS concerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id BIGINT REFERENCES artists(id) ON DELETE CASCADE,
    event_name TEXT NOT NULL,
    city TEXT NOT NULL,
    venue TEXT NOT NULL,
    event_date DATE NOT NULL,
    ticket_url TEXT,
    source TEXT DEFAULT 'lastfm',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT unique_artist_date_city UNIQUE (artist_id, event_date, city)
);

-- Enable RLS on both tables
ALTER TABLE artists ENABLE ROW LEVEL SECURITY;
ALTER TABLE concerts ENABLE ROW LEVEL SECURITY;

-- Security Policies for artists table
DROP POLICY IF EXISTS "Allow anon read access" ON artists;
DROP POLICY IF EXISTS "Allow anon insert access" ON artists;
DROP POLICY IF EXISTS "Allow anon update access" ON artists;
DROP POLICY IF EXISTS "Allow anon delete access" ON artists;

CREATE POLICY "Allow anon read access" ON artists FOR SELECT USING (true);
CREATE POLICY "Allow anon insert access" ON artists FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon update access" ON artists FOR UPDATE USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon delete access" ON artists FOR DELETE USING (true);

-- Security Policies for concerts table
DROP POLICY IF EXISTS "Allow anon read access" ON concerts;
DROP POLICY IF EXISTS "Allow anon insert access" ON concerts;
DROP POLICY IF EXISTS "Allow anon update access" ON concerts;
DROP POLICY IF EXISTS "Allow anon delete access" ON concerts;

CREATE POLICY "Allow anon read access" ON concerts FOR SELECT USING (true);
CREATE POLICY "Allow anon insert access" ON concerts FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon update access" ON concerts FOR UPDATE USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon delete access" ON concerts FOR DELETE USING (true);

-- Playlist History table
CREATE TABLE IF NOT EXISTS playlist_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id TEXT UNIQUE NOT NULL,
    track_name TEXT NOT NULL,
    artist_id TEXT NOT NULL,
    artist_name TEXT NOT NULL,
    tier TEXT NOT NULL,
    monthly_listeners BIGINT,
    release_date DATE,
    added_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS on playlist_history table
ALTER TABLE playlist_history ENABLE ROW LEVEL SECURITY;

-- Security Policies for playlist_history table
DROP POLICY IF EXISTS "Allow anon read access" ON playlist_history;
DROP POLICY IF EXISTS "Allow anon insert access" ON playlist_history;
DROP POLICY IF EXISTS "Allow anon update access" ON playlist_history;
DROP POLICY IF EXISTS "Allow anon delete access" ON playlist_history;

CREATE POLICY "Allow anon read access" ON playlist_history FOR SELECT USING (true);
CREATE POLICY "Allow anon insert access" ON playlist_history FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon update access" ON playlist_history FOR UPDATE USING (true) WITH CHECK (true);
CREATE POLICY "Allow anon delete access" ON playlist_history FOR DELETE USING (true);
